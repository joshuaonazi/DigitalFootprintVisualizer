import { useState, useEffect } from 'react'
import { generateReport } from '../services/claudeService'

export default function MyReport() {
  const [report, setReport] = useState(null)
  const [loading, setLoading] = useState(false)
  const [generated, setGenerated] = useState(false)

  const riskResult = (() => {
    try {
      const stored = localStorage.getItem('riskResult')
      return stored ? JSON.parse(stored) : null
    } catch { return null }
  })()

  const quizScore = (() => {
    try {
      const stored = localStorage.getItem('quizScore')
      return stored ? JSON.parse(stored) : null
    } catch { return null }
  })()

  useEffect(() => {
    const stored = localStorage.getItem('generatedReport')
    if (stored) {
      setReport(stored)
      setGenerated(true)
    }
  }, [])

  const handleGenerate = async () => {
    setLoading(true)
    try {
      const result = await generateReport(riskResult)
      setReport(result)
      setGenerated(true)
      localStorage.setItem('generatedReport', result)
    } catch (err) {
      console.error(err)
    } finally {
      setLoading(false)
    }
  }

  const handlePrint = () => {
    window.print()
  }

  const tierColors = {
    Low: { bg: 'bg-emerald-500/10', border: 'border-emerald-500/30', text: 'text-emerald-400' },
    Medium: { bg: 'bg-amber-500/10', border: 'border-amber-500/30', text: 'text-amber-400' },
    High: { bg: 'bg-orange-500/10', border: 'border-orange-500/30', text: 'text-orange-400' },
    Critical: { bg: 'bg-red-500/10', border: 'border-red-500/30', text: 'text-red-400' },
  }

  const tier = riskResult ? tierColors[riskResult.riskTier] : tierColors.High

  if (!riskResult) {
    return (
      <div className="px-4 py-10">
        <div className="max-w-3xl mx-auto text-center">
          <div className="bg-gray-900 border border-gray-800 rounded-2xl p-12">
            <p className="text-4xl mb-4">📋</p>
            <h2 className="text-white text-xl font-bold mb-2">No Data Yet</h2>
            <p className="text-gray-400 text-sm mb-6">
              Complete the survey first to generate your personalised privacy audit report.
            </p>
            <button
              onClick={() => window.location.href = '/survey'}
              className="bg-violet-600 hover:bg-violet-700 text-white font-semibold px-6 py-3 rounded-xl transition-colors"
            >
              Take Survey →
            </button>
          </div>
        </div>
      </div>
    )
  }

  return (
    <div className="px-4 py-10 print:py-4 print:px-8">
      <div className="max-w-3xl mx-auto">

        {/* Header */}
        <div className="mb-8 flex flex-col gap-4 sm:flex-row sm:items-start sm:justify-between print:mb-4">
          <div>
            <h1 className="text-white text-3xl font-bold mb-1 print:text-black">
              My Privacy Audit Report
            </h1>
            <p className="text-gray-400 text-sm print:text-gray-600">
              Generated by DFV AI System · University of Ibadan
            </p>
          </div>
          <div className="flex flex-col gap-2 sm:flex-row sm:gap-3 print:hidden">
            {!generated && (
              <button
                onClick={handleGenerate}
                disabled={loading}
                className="bg-violet-600 hover:bg-violet-700 disabled:opacity-50 text-white font-semibold px-5 py-2.5 rounded-xl transition-colors text-sm"
              >
                {loading ? '⏳ Generating...' : '✨ Generate Report'}
              </button>
            )}
            {generated && (
              <button
                onClick={handlePrint}
                className="bg-gray-800 hover:bg-gray-700 text-white font-medium px-5 py-2.5 rounded-xl transition-colors text-sm"
              >
                🖨️ Print / Save PDF
              </button>
            )}
            {generated && (
              <button
                onClick={() => {
                  localStorage.removeItem('generatedReport')
                  setReport(null)
                  setGenerated(false)
                }}
                className="bg-gray-800 hover:bg-gray-700 text-gray-400 font-medium px-4 py-2.5 rounded-xl transition-colors text-sm"
              >
                Regenerate
              </button>
            )}
          </div>
        </div>

        {/* Score summary card */}
        <div className={`rounded-2xl p-6 mb-6 border ${tier.bg} ${tier.border}`}>
          <div className="flex flex-col justify-between gap-4 sm:flex-row sm:items-center">
            <div>
              <p className="text-gray-400 text-sm mb-1">Overall Privacy Risk Score</p>
              <div className="flex items-baseline gap-3">
                <span className={`text-6xl font-black ${tier.text}`}>
                  {riskResult.overallScore}
                </span>
                <span className={`text-lg font-bold ${tier.text}`}>/ 100</span>
              </div>
              <span className={`inline-block mt-2 px-3 py-1 rounded-full text-xs font-bold border ${tier.bg} ${tier.border} ${tier.text}`}>
                {riskResult.riskTier} Risk
              </span>
            </div>
            <div className="sm:text-right">
              <p className="text-gray-500 text-xs mb-2">Dimension Scores</p>
              {Object.entries(riskResult.dimensions).map(([key, val]) => (
                <div key={key} className="flex items-center gap-2 sm:justify-end mb-1">
                  <span className="text-gray-400 text-xs capitalize">
                    {key.replace(/([A-Z])/g, ' $1').trim()}
                  </span>
                  <span className={`text-xs font-bold w-8 text-right ${
                    val.score > 70 ? 'text-red-400' :
                    val.score > 40 ? 'text-amber-400' : 'text-emerald-400'
                  }`}>
                    {val.score}
                  </span>
                </div>
              ))}
            </div>
          </div>
        </div>

        {/* Quiz score if available */}
        {quizScore && (
          <div className="bg-gray-900 border border-gray-800 rounded-2xl p-4 mb-6 flex items-center justify-between">
            <div>
              <p className="text-gray-400 text-sm">Awareness Quiz Score</p>
              <p className="text-white font-bold">{quizScore.score}/{quizScore.total} correct ({quizScore.percentage}%)</p>
            </div>
            <div className={`text-2xl font-black ${
              quizScore.percentage >= 70 ? 'text-emerald-400' :
              quizScore.percentage >= 50 ? 'text-amber-400' : 'text-red-400'
            }`}>
              {quizScore.percentage >= 70 ? '🏆' : quizScore.percentage >= 50 ? '📚' : '💪'}
            </div>
          </div>
        )}

        {/* Generate prompt */}
        {!generated && !loading && (
          <div className="bg-violet-600/10 border border-violet-500/30 rounded-2xl p-8 text-center">
            <p className="text-4xl mb-4">✨</p>
            <h2 className="text-white text-xl font-bold mb-2">
              Generate Your Full Report
            </h2>
            <p className="text-gray-400 text-sm max-w-md mx-auto mb-6">
              Click the button above to generate your personalised AI-powered privacy audit report based on your survey results.
            </p>
          </div>
        )}

        {/* Loading state */}
        {loading && (
          <div className="bg-gray-900 border border-gray-800 rounded-2xl p-12 text-center">
            <div className="inline-flex gap-1 mb-4">
              <div className="w-3 h-3 rounded-full bg-violet-600 animate-bounce" style={{ animationDelay: '0ms' }} />
              <div className="w-3 h-3 rounded-full bg-violet-600 animate-bounce" style={{ animationDelay: '150ms' }} />
              <div className="w-3 h-3 rounded-full bg-violet-600 animate-bounce" style={{ animationDelay: '300ms' }} />
            </div>
            <p className="text-white font-semibold mb-1">Generating your report...</p>
            <p className="text-gray-500 text-sm">AI is analysing your footprint data</p>
          </div>
        )}

        {/* Report content */}
        {generated && report && (
          <div className="bg-gray-900 border border-gray-800 rounded-2xl p-8 print:bg-white print:border-gray-200">
            <div className="flex items-center gap-2 mb-6 pb-4 border-b border-gray-800 print:border-gray-200">
              <span className="text-2xl">📄</span>
              <div>
                <h2 className="text-white font-bold print:text-black">
                  Privacy Audit Report
                </h2>
                <p className="text-gray-500 text-xs print:text-gray-600">
                  Digital Footprint Visualizer · University of Ibadan · {new Date().toLocaleDateString()}
                </p>
              </div>
            </div>
            <div className="prose prose-invert max-w-none print:prose-slate">
              {report.split('\n').map((line, i) => {
                if (!line.trim()) return <div key={i} className="h-3" />
                if (line.startsWith('PRIVACY AUDIT REPORT') || line.startsWith('###')) {
                  return null
                }
                if (line.toUpperCase() === line && line.length > 3 && !line.startsWith('•') && !line.startsWith('-') && !line.startsWith('Priority')) {
                  return (
                    <h3 key={i} className="text-violet-400 font-bold text-sm uppercase tracking-wider mt-6 mb-2 print:text-violet-600">
                      {line}
                    </h3>
                  )
                }
                if (line.startsWith('•') || line.startsWith('-') || line.startsWith('Priority')) {
                  return (
                    <div key={i} className="flex items-start gap-2 mb-2">
                      <span className="text-violet-400 mt-0.5 flex-shrink-0">▸</span>
                      <p className="text-gray-300 text-sm leading-relaxed print:text-gray-700">
                        {line.replace(/^[•\-]\s*/, '')}
                      </p>
                    </div>
                  )
                }
                return (
                  <p key={i} className="text-gray-300 text-sm leading-relaxed mb-3 print:text-gray-700">
                    {line}
                  </p>
                )
              })}
            </div>
          </div>
        )}

      </div>
    </div>
  )
}